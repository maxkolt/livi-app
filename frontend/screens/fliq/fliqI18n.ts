const TABLES: Record<Lang, Table> = {
  ru,
  en,
  es,
  de,
  fr,
  it,
  pt,
  tr,
  ar,
  ja,
  ko,
  zh,
  'zh-TW': zhTW,
  hi,
  vi,
  th,
  id,
};

export function fliqT(key: string, lang: Lang, vars?: Record<string, string>): string {
  let s = TABLES[lang]?.[key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
  return s;
}
